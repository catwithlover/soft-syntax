const languageButtons = document.querySelectorAll("[data-language]");
const copyButton = document.querySelector("[data-copy-target]");
const copyButtonLabel = copyButton.querySelector("span");
const commandStatus = document.querySelector(".command-status");
const description = document.querySelector('meta[name="description"]');
const imageryFormula = document.querySelector(".imagery-formula");
let currentLanguage = "en";
let copyResetTimer;

function readSavedLanguage() {
  try {
    return localStorage.getItem("soft-syntax-language");
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem("soft-syntax-language", language);
  } catch {
    // The language still changes when storage is unavailable.
  }
}

function setLanguage(language, persist = true) {
  currentLanguage = translations[language] ? language : "en";
  const strings = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = strings.documentTitle;
  description.setAttribute("content", strings.description);
  imageryFormula.setAttribute("aria-label", strings.formulaAria);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (strings[key]) element.textContent = strings[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (strings[key]) element.setAttribute("alt", strings[key]);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (strings[key]) element.setAttribute("aria-label", strings[key]);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });

  commandStatus.textContent = "";
  copyButtonLabel.textContent = strings.copyButton;
  if (persist) saveLanguage(currentLanguage);
}

async function copyInstallCommand() {
  const command = document.getElementById(copyButton.dataset.copyTarget).textContent.trim();
  const strings = translations[currentLanguage];

  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(command);
    } else {
      const textArea = document.createElement("textarea");
      textArea.value = command;
      textArea.setAttribute("readonly", "");
      textArea.style.position = "fixed";
      textArea.style.opacity = "0";
      document.body.append(textArea);
      textArea.select();
      const copied = document.execCommand("copy");
      textArea.remove();
      if (!copied) throw new Error("Copy command failed");
    }

    copyButtonLabel.textContent = strings.copiedButton;
    commandStatus.textContent = strings.copySuccess;
  } catch {
    commandStatus.textContent = strings.copyError;
  }

  window.clearTimeout(copyResetTimer);
  copyResetTimer = window.setTimeout(() => {
    copyButtonLabel.textContent = translations[currentLanguage].copyButton;
    commandStatus.textContent = "";
  }, 2400);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

copyButton.addEventListener("click", copyInstallCommand);
setLanguage(readSavedLanguage() || "en", false);
